#!/usr/bin/env python3
"""Re-derive every `line` in the defect manifest from the fixture itself.

The manifest records where each seeded defect lives. Hand-maintained line
numbers drift the moment a fixture file is edited, so this script finds each
defect by the code it is about and rewrites the number. Run it after touching
any file under benchmarks/fixtures/defect_corpus/:

    python tools/sync_defect_lines.py --check    # fail if lines are stale
    python tools/sync_defect_lines.py            # rewrite them
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "benchmarks" / "fixtures" / "defect_corpus" / "defects.json"

# defect id -> (fixture-relative file, the exact code the defect is about)
ANCHORS: dict[str, tuple[str, str]] = {
    "D01": ("app/security.py", "return eval(raw)"),
    "D02": ("app/security.py", 'subprocess.run("ls -l " + user_input, shell=True)'),
    "D03": ("app/security.py", 'return os.system("cat " + name)'),
    "D04": ("app/security.py", "return pickle.loads(blob)"),
    "D05": ("app/security.py", 'PASSWORD = "Sup3rSecret!Passw0rd"'),
    "D06": ("app/security.py", 'API_TOKEN = "ghp_'),
    "D07": ("app/security.py", "DEBUG = True"),
    "D24": ("app/security.py", "hashlib.md5(value.encode(\"utf-8\")).hexdigest()"),
    "DECOY1": ("app/security.py", "usedforsecurity=False"),
    "D25": ("app/security.py", "return yaml.load(blob)"),
    "D08": ("app/views.py", "    except:"),
    "D09": ("app/views.py", "    import socket"),
    "D10": ("app/views.py", "display_name}"),
    "D11": ("app/views.py", 'query = "SELECT * FROM accounts'),
    "D12": ("app/views.py", 'filename = "/tmp/app-config-"'),
    "D13": ("app/utils.py", "def classify(value: int"),
    "D15": ("requirements.txt", "flask"),
    "D16": ("app/broken.py", "def broken(:"),
    "D17": ("app/cycle_a.py", "import app.cycle_b"),
    # D18 and D19 are generated by the harness, D14/D20-D23 are project-level.
}


def find_line(fixture: Path, file_name: str, anchor: str) -> int:
    path = fixture / file_name
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if anchor in line:
            return number
    raise SystemExit(f"anchor {anchor!r} not found in {file_name}")


def sync(check: bool) -> int:
    spec = json.loads(MANIFEST.read_text(encoding="utf-8"))
    fixture = MANIFEST.parent
    stale: list[str] = []
    for entry in spec["defects"]:
        anchor = ANCHORS.get(entry["id"])
        if anchor is None:
            continue
        expected = find_line(fixture, anchor[0], anchor[1])
        if entry["line"] != expected:
            stale.append(f"{entry['id']}: {entry['line']} -> {expected} ({anchor[0]})")
            if not check:
                entry["line"] = expected
    if not stale:
        print("defect manifest line numbers are current")
        return 0
    if check:
        print("stale defect line numbers (run `python tools/sync_defect_lines.py`):")
        for item in stale:
            print(f"  {item}")
        return 1
    MANIFEST.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("updated:")
    for item in stale:
        print(f"  {item}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Exit 1 when a line number is stale")
    args = parser.parse_args(argv)
    return sync(args.check)


if __name__ == "__main__":
    sys.exit(main())
